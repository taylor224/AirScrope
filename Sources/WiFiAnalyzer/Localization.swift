@MainActor func L(_ key: String, _ arguments: String...) -> String {
    let language = AppSettings.shared.language.resolved
    let index = language == "zh" ? 1 : 0
    var text = descriptions[key]?[language == "ko" ? 0 : language == "en" ? 1 : 2] ?? (language == "ko" ? key : translations[key]?[index] ?? key)
    if key == "제조사 안내 {0}" && language == "ko" {
        text = "제조사는 IEEE MAC 주소 등록기관으로 실제 기기 브랜드와 다를 수 있습니다. 로컬 관리 주소는 추정하지 않습니다. 데이터 기준: {0}."
    }
    for (index, value) in arguments.enumerated() { text = text.replacingOccurrences(of: "{\(index)}", with: value) }
    return text
}
