@MainActor func networkTitle(_ network: NetworkRecord) -> String {
    if let ssid = network.ssid, !ssid.isEmpty { return ssid }
    return L(network.name)
}
@MainActor func findingText(_ finding: Finding) -> (title: String, detail: String) {
    var key = "finding." + finding.id
    if finding.id == "signal" || finding.id == "snr" { key += finding.severity == .warning ? ".warning" : ".good" }
    func format(_ template: String) -> String {
        var text = L(template)
        for (index, value) in finding.values.enumerated() { text = text.replacingOccurrences(of: "{\(index)}", with: value) }
        return text
    }
    return (format(key + ".title"), format(key + ".detail"))
}

